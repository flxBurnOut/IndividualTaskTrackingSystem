"""Paint-only progress reveals; business values and accessible counts stay final."""
from __future__ import annotations

import weakref

from PySide6.QtCore import QEasingCurve, QEvent, QObject, QRectF, Qt, QTimer, QVariantAnimation
from PySide6.QtGui import QBrush, QColor, QLinearGradient, QPainter, QPainterPath
from PySide6.QtWidgets import QProgressBar

from .gui_materials import reduce_motion
from .gui_theme import bind_theme, color


def gradient_colors(role='primary'):
    """A restrained sheen, darkened/lightened away from the text foreground."""
    base = QColor(color(role))
    text = QColor(color('chart_on_unknown' if role == 'unreported' else 'chart_on_color'))
    shade = base.darker(110) if text.lightnessF() > .5 else base.lighter(108)
    return shade, base


def progress_brush(rect, role='primary', *, vertical=False):
    start, end = gradient_colors(role)
    gradient = QLinearGradient(rect.bottomLeft(), rect.topRight() if vertical else rect.bottomRight())
    gradient.setColorAt(0, start)
    gradient.setColorAt(1, end)
    return QBrush(gradient)


class ProgressReveal(QObject):
    """Run once after visible data arrives, including widgets rebuilt by polling.

    A stable page and key can share the first-display marker across replacement
    widgets. Only local paint state changes during animation; no valueChanged,
    queries or persistence operations are generated by its frames.
    """
    def __init__(self, widget):
        super().__init__(widget)
        self._widget = weakref.ref(widget)
        self.fraction = 0.0
        self.ready = False
        self.started = False
        self._scope = weakref.ref(widget)
        self._key = 'progress'
        self.animation = QVariantAnimation(self)
        self.animation.setDuration(650)
        self.animation.setEasingCurve(QEasingCurve.Type.OutCubic)
        self.animation.setStartValue(0.0)
        self.animation.setEndValue(1.0)
        self.animation.valueChanged.connect(self._frame)
        widget.installEventFilter(self)
        bind_theme(widget, self.refresh_theme)

    @property
    def widget(self):
        return self._widget()

    def set_scope(self, scope, key):
        self._scope, self._key = weakref.ref(scope), key
        if key in getattr(scope, '_progress_revealed_keys', ()):
            self.started = True
            self.finish()

    def _frame(self, value):
        if reduce_motion():
            self.finish()
            return
        self.fraction = float(value)
        self.widget.update()

    def finish(self):
        self.animation.stop()
        self.fraction = 1.0
        self.widget.update()

    def refresh_theme(self):
        if self.started and reduce_motion():
            self.finish()
        self.widget.update()

    def set_ready(self, ready):
        self.ready = bool(ready)
        if self.ready:
            self._start_if_visible()
        elif self.started:
            self.finish()
        self.widget.update()

    def _start_if_visible(self):
        if self.started or not self.ready or not self.widget.isVisible():
            return
        self.started = True
        scope = self._scope()
        if scope is not None:
            seen = getattr(scope, '_progress_revealed_keys', None)
            if seen is None:
                seen = scope._progress_revealed_keys = set()
            if self._key in seen:
                self.finish()
                return
            seen.add(self._key)
        if reduce_motion():
            self.finish()
        else:
            self.animation.start()

    def eventFilter(self, watched, event):
        if event.type() == QEvent.Type.Show:
            # Let layouts settle and initial asynchronous data arrive first.
            QTimer.singleShot(0, self._start_if_visible)
        elif event.type() == QEvent.Type.Hide and self.started:
            self.finish()
        return False


class AnimatedProgressBar(QProgressBar):
    """QProgressBar API/accessibility with a separate finite visual reveal."""
    def __init__(self, parent=None, *, reveal_scope=None, reveal_key='progress'):
        super().__init__(parent)
        self.reveal = ProgressReveal(self)
        if reveal_scope is not None:
            self.reveal.set_scope(reveal_scope, reveal_key)
        self.valueChanged.connect(self._value_changed)

    def _value_changed(self, value):
        self.reveal.set_ready(self.maximum() > self.minimum() and value > self.minimum())

    def paintEvent(self, event):
        if self.maximum() == self.minimum():
            # Native busy indicators have no known denominator to animate.
            return super().paintEvent(event)
        painter = QPainter(self)
        painter.setRenderHint(QPainter.RenderHint.Antialiasing)
        rect = QRectF(self.rect())
        radius = min(6.0, rect.height() / 2)
        path = QPainterPath()
        path.addRoundedRect(rect, radius, radius)
        painter.setClipPath(path)
        painter.fillRect(rect, QColor(color('chart_track')))
        ratio = max(0.0, min(1.0, (self.value() - self.minimum()) / (self.maximum() - self.minimum())))
        width = rect.width() * ratio * self.reveal.fraction
        filled = QRectF(rect.left(), rect.top(), width, rect.height())
        painter.fillRect(filled, progress_brush(rect))
        if self.isTextVisible():
            painter.setClipping(False)
            painter.setPen(QColor(color('text')))
            painter.drawText(rect, Qt.AlignmentFlag.AlignCenter, self.text())
            painter.setClipRect(filled)
            painter.setPen(QColor(color('primary_text')))
            painter.drawText(rect, Qt.AlignmentFlag.AlignCenter, self.text())
        painter.end()
